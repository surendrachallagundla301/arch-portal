CREATE TABLE architecture_request (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title             VARCHAR(150)  NOT NULL,
    application_name  VARCHAR(100)  NOT NULL,
    application_owner VARCHAR(150),
    description       VARCHAR(4000) NOT NULL,
    status            VARCHAR(20)   NOT NULL,
    submitted_by      VARCHAR(100)  NOT NULL,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    version           BIGINT        NOT NULL DEFAULT 0
);

CREATE INDEX idx_architecture_request_status ON architecture_request (status);
CREATE INDEX idx_architecture_request_created ON architecture_request (created_at);

CREATE TABLE review_decision (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id  BIGINT        NOT NULL REFERENCES architecture_request (id) ON DELETE CASCADE,
    outcome     VARCHAR(20)   NOT NULL,
    notes       VARCHAR(2000) NOT NULL,
    decided_by  VARCHAR(100)  NOT NULL,
    decided_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_review_decision_request ON review_decision (request_id);

CREATE TABLE decision_action_item (
    decision_id BIGINT       NOT NULL REFERENCES review_decision (id) ON DELETE CASCADE,
    item_order  INT          NOT NULL,
    item        VARCHAR(500) NOT NULL,
    PRIMARY KEY (decision_id, item_order)
);
